  async function _calendarDbEvents(provider, dbPath) {
    const base = _normalizeFolderPath(dbPath);
    const rows = [];
    const entries = await _listDirectoryEntries(provider, base);
    for (const entry of entries) {
      if (entry.handle.kind !== 'file' || !entry.name.endsWith('.md') || entry.name === _basename(base) + '.md') continue;
      const filePath = _joinPath(base, entry.name);
      const parsed = await _readFrontmatterFile(provider, filePath);
      if (parsed.frontmatter.type !== 'calendar-event') continue;
      rows.push({
        ...parsed.frontmatter,
        id: entry.name.replace(/\.md$/i, ''),
        name: entry.name.replace(/\.md$/i, ''),
        path: filePath,
        body: String(parsed.body || '').trim(),
        members: Array.isArray(parsed.frontmatter.members) ? parsed.frontmatter.members : [],
      });
    }
    return rows.sort((a, b) => String(a.start || '').localeCompare(String(b.start || '')));
  }

